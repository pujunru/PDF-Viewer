def esc(s: str) -> str:
    return s.replace("\\", r"\\").replace("(", r"\(").replace(")", r"\)")


def content_stream(blocks) -> bytes:
    """Lays a page out top-down, choosing size and leading per block kind."""
    out = ["BT"]
    y = 742
    for kind, text in blocks:
        if kind == "H":
            out.append(f"/F2 24 Tf 1 0 0 1 72 {y} Tm ({esc(text)}) Tj")
            y -= 42
        elif kind == "S":
            y -= 8
            out.append(f"/F2 13 Tf 1 0 0 1 72 {y} Tm ({esc(text)}) Tj")
            y -= 24
        else:
            out.append(f"/F1 11 Tf 1 0 0 1 72 {y} Tm ({esc(text)}) Tj")
            y -= 17
    out.append("ET")
    return zlib.compress("\n".join(out).encode("latin-1"))


def build() -> bytes:
    objs: list[bytes] = []

    def add(b: bytes) -> int:
        objs.append(b)
        return len(objs)  # object numbers are 1-based

    font_regular = add(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica "
                       b"/Encoding /WinAnsiEncoding >>")
    font_bold = add(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold "
                    b"/Encoding /WinAnsiEncoding >>")

    # The pages tree must know its children before they exist, so its object
    # number is reserved here and its body is written once the ids are known.
    pages_id = add(b"")

    page_ids = []
    for _title, blocks in PAGES:
        data = content_stream(blocks)
        stream_id = add(b"<< /Length %d /Filter /FlateDecode >>\nstream\n" % len(data)
                        + data + b"\nendstream")
        page_ids.append(add(
            b"<< /Type /Page /Parent %d 0 R /MediaBox [0 0 612 792] "
            b"/Resources << /Font << /F1 %d 0 R /F2 %d 0 R >> >> "
            b"/Contents %d 0 R >>" % (pages_id, font_regular, font_bold, stream_id)))

    kids = b" ".join(b"%d 0 R" % i for i in page_ids)
    objs[pages_id - 1] = (b"<< /Type /Pages /Count %d /Kids [%s] >>"
                          % (len(page_ids), kids))

    catalog = add(b"<< /Type /Catalog /Pages %d 0 R >>" % pages_id)
    info = add(b"<< /Title (PDF Viewer \\226 Sample Document) "
               b"/Producer (tools/make-sample-pdf.py) >>")

    # Serialize, recording each object's byte offset for the xref table.
    buf = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets = []
    for n, body in enumerate(objs, start=1):
        offsets.append(len(buf))
        buf += b"%d 0 obj\n" % n + body + b"\nendobj\n"

    xref_at = len(buf)
    buf += b"xref\n0 %d\n" % (len(objs) + 1)
    buf += b"0000000000 65535 f \n"
    for off in offsets:
        buf += b"%010d 00000 n \n" % off
    buf += (b"trailer\n<< /Size %d /Root %d 0 R /Info %d 0 R >>\nstartxref\n%d\n%%%%EOF\n"
            % (len(objs) + 1, catalog, info, xref_at))
    return bytes(buf)


if __name__ == "__main__":
    # The viewer document loads ./sample.pdf relative to itself, so the file
    # belongs beside viewer.html rather than next to this script.
    dest = Path(__file__).resolve().parent.parent / "packages/viewer/src/sample.pdf"
    out = build()
    dest.write_bytes(out)
    print(f"wrote {dest} ({len(out):,} bytes, {len(PAGES)} pages)")
