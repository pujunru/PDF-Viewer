#!/usr/bin/env python3
"""
Generates the viewer's bundled sample document.

Written by hand rather than with a PDF library so the repo needs no extra build
dependency to reproduce it. The output deliberately exercises the features the
viewer implements: real (selectable, searchable) text so the text layer and
search have something to bind to, and several pages so paging and scroll work.
"""
import zlib
from pathlib import Path

